import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import ts from "typescript";
import { createRequire } from "node:module";
import path from "node:path";

// No legacy catalogs, aliases, migration tables or held-out files are inputs.
const schemaText = readFileSync("lib/menu-schema.ts", "utf8");
const schemaDir = path.resolve(".data/menu-validation");
mkdirSync(schemaDir, { recursive: true });
writeFileSync(path.join(schemaDir, "schema.cjs"), ts.transpileModule(schemaText, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText);
const { validateMenu } = createRequire(import.meta.url)(path.join(schemaDir, "schema.cjs"));
const bytes = readFileSync("lib/menu-source.json");
const source = JSON.parse(bytes);
const validation = validateMenu(source);
const menuApproved = /\bapproved by the restaurant\b/i.test(source.status) && !/\bnot (?:yet )?approved\b/i.test(source.status);
const aliases = JSON.parse(readFileSync("lib/menu-aliases.json", "utf8"));
assert.deepEqual(Object.keys(aliases).sort(), source.items.map(item => item.id).sort(), "Alias IDs must exactly match the final menu");
for (const values of Object.values(aliases)) assert.ok(Array.isArray(values) && values.every(value => typeof value === "string" && value.length > 0));
const preserved = JSON.parse(readFileSync("lib/menu-preserved.json", "utf8"));
const restaurant = { ...preserved.restaurant, name: source.restaurant.name, address: source.restaurant.address,
  phone: source.restaurant.phone_listed_on_website, addressNeedsReview: false, menuApproved,
  demoStatus: menuApproved ? "DEMO — menu approved by the restaurant" : "DEMO — menu approval pending", websiteFulfillment: source.restaurant.fulfillment_listed_on_website,
  pickupEtaSource: source.restaurant.pickup_eta_listed_on_website, hoursSourceNote: source.restaurant.hours_note,
  hoursNeedsReview: true };
const sha = createHash("sha256").update(bytes).digest("hex");
const generated = '// GENERATED by npm run menu:import. Only menu source: lib/menu-source.json.\n' +
  'import { validateMenu, MenuSource, MenuItem } from "./menu-schema";\nexport { unitPriceCents } from "./menu-schema";\nexport type { MenuItem } from "./menu-schema";\n' +
  `const SOURCE = ${JSON.stringify(source, null, 2)} as MenuSource;\n` +
  `export const MENU_VALIDATION = validateMenu(SOURCE);\nexport const MENU_SOURCE_SHA256 = ${JSON.stringify(sha)};\n` +
  `export const MODIFIERS = SOURCE.modifiers;\nexport const RESTAURANT = ${JSON.stringify(restaurant, null, 2)};\n` +
  `export const CATERING = ${JSON.stringify(preserved.catering, null, 2)};\n` +
  '// Recognition aliases remain separate from source menu data.\nimport ALIASES from "./menu-aliases.json";\n' +
  'export const MENU: MenuItem[] = SOURCE.items.map(item => ({ ...item, aliases: (ALIASES as Record<string,string[]>)[item.id] }));\n' +
  'export const CATEGORIES = [...new Set(MENU.map(item => item.category))];\n' +
  'export function getItem(id: string) { return MENU.find(item => item.id === id); }\n' +
  'export function menuAsText() { return MENU.map(item => `${item.name}: ${item.price_cents} cents${item.size ? ` Half; Full ${item.price_cents + item.size.Full} cents` : ""}`).join("\\n"); }\n';
if (process.argv.includes("--check")) {
  assert.equal(readFileSync("lib/menu.ts", "utf8"), generated, "Generated menu stale; run npm run menu:import");
} else {
  writeFileSync("lib/menu.ts", generated);
  mkdirSync("eval/results", { recursive: true });
  const registry = { source: "lib/menu-source.json", sourceSha256: sha, approved: menuApproved, ...validation,
    address: restaurant.address, phone: restaurant.phone, items: source.items.map(({id,name,price_cents,size,size_verified,spice}) => ({id,name,price_cents,size,size_verified,spice})) };
  writeFileSync("eval/results/menu-id-registry.json", JSON.stringify(registry, null, 2) + "\n");
  writeFileSync("eval/results/menu-item-ids.txt", source.items.map(item => item.id).join("\n") + "\n");
  writeFileSync("eval/results/menu-id-registry.md", ["# Final menu registry", "", restaurant.demoStatus, "",
    "IDs are used verbatim from the final JSON; no IDs or prices are inherited from earlier menus.", "",
    `Validation: ${JSON.stringify(validation)}. Address: ${restaurant.address}. Phone: ${restaurant.phone}.`, "",
    "Full price is base cents plus the Full surcharge. Source provenance flags are retained verbatim. The supplied menu and its prices are approved by the restaurant.", "",
    "| ID | Name | Base cents | Full cents | Spice | Size verified |", "| --- | --- | ---: | ---: | --- | --- |",
    ...source.items.map(item => `| ${item.id} | ${item.name} | ${item.price_cents} | ${item.size ? item.price_cents + item.size.Full : "—"} | ${item.spice} | ${item.size ? item.size_verified : "—"} |`), ""].join("\n"));
}
console.log(`Final menu validated: ${JSON.stringify(validation)}. Approved: ${menuApproved}. Held-out not accessed.`);
